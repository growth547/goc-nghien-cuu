// Single entry point that refreshes every data source of /du-lieu/ and rebuilds the rich pages.
//
//   node scripts/fetch-data.mjs                 refresh all sources (incremental), rebuild pages
//   node scripts/fetch-data.mjs wdi pink        refresh only these sources, rebuild pages from caches
//   node scripts/fetch-data.mjs --force         ignore "unchanged" shortcuts and re-download everything
//   node scripts/fetch-data.mjs --build-only    no network: rebuild pages from the cached raw files
//
// Step 1 (per source, see scripts/data-lib/sources.mjs): download Viet Nam series (+ ASEAN/China peers for
//   indicators with a rich page) into src/data/du-lieu/raw/<source>.json. A source whose request fails keeps
//   its previous raw file; sources that report no change since the last run are not re-downloaded.
// Step 2: write one JSON per rich indicator (scripts/indicators/*.mjs) into src/content/du-lieu/<slug>.json.
//   If a rich indicator is missing from the fresh data, its previous page file is kept.
// The "Kho chỉ số" explorer, the panel CSVs and the per-page CSVs are generated by Astro at build time from
// the same raw files. Licences: scripts/data-sources.mjs. Validate afterwards: node scripts/check-data.mjs
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { FETCHERS } from "./data-lib/sources.mjs";
import { RICH, THEMES, validateRich } from "./indicators/index.mjs";
import { ASEAN_PEERS, SOURCES } from "./data-sources.mjs";

const RAW_DIR = new URL("../src/data/du-lieu/raw/", import.meta.url);
const OUT_DIR = new URL("../src/content/du-lieu/", import.meta.url);
const args = process.argv.slice(2);
const force = args.includes("--force");
const buildOnly = args.includes("--build-only");
const only = args.filter(a => !a.startsWith("--"));
const unknown = only.filter(s => !FETCHERS[s]);
if (unknown.length) {
  console.error(`Unknown source(s): ${unknown.join(", ")}. Known: ${Object.keys(FETCHERS).join(", ")}`);
  process.exit(1);
}
validateRich();
mkdirSync(RAW_DIR, { recursive: true });
mkdirSync(OUT_DIR, { recursive: true });

const rawFile = id => new URL(`${id}.json`, RAW_DIR);
const readRaw = id => (existsSync(rawFile(id)) ? JSON.parse(readFileSync(rawFile(id), "utf8")) : null);
const summary = [];

// ---------------------------------------------------------------- step 1: sources
for (const id of Object.keys(FETCHERS)) {
  const cached = readRaw(id);
  if (buildOnly || (only.length && !only.includes(id))) {
    summary.push({ id, status: cached ? "cached" : "MISSING", series: cached ? Object.keys(cached.series).length : 0 });
    continue;
  }
  const peerCodes = new Set(RICH.filter(r => r.source === id).map(r => r.code));
  const t0 = Date.now();
  try {
    const fresh = await FETCHERS[id]({ cached, peerCodes, force, log: m => console.log(`  ${m}`) });
    const n = Object.keys(fresh.series).length;
    if (!n) throw new Error("no series returned");
    if (cached && n < Object.keys(cached.series).length * 0.8) {
      throw new Error(`only ${n} series vs ${Object.keys(cached.series).length} cached; refusing to shrink the cache`);
    }
    writeFileSync(rawFile(id), JSON.stringify(fresh) + "\n", "utf8");
    summary.push({ id, status: fresh === cached ? "unchanged" : "updated", series: n, secs: (Date.now() - t0) / 1000, lastUpdated: fresh.lastUpdated });
  } catch (e) {
    console.error(`FAIL ${id}: ${e.message}`);
    summary.push({ id, status: cached ? "FAILED (kept old file)" : "FAILED (no data)", series: cached ? Object.keys(cached.series).length : 0 });
  }
}

// ---------------------------------------------------------------- step 2: rich pages
const raws = Object.fromEntries(Object.keys(FETCHERS).map(id => [id, readRaw(id)]));
const cap = s => s.charAt(0).toLocaleUpperCase("vi") + s.slice(1);
const clean = v => Number(Number(v).toPrecision(12));
const SRC_SHORT = {
  wdi: "World Bank",
  wgi: "World Bank (WGI)",
  gfdd: "World Bank (GFDD)",
  pink: "World Bank",
  pwt: "Penn World Table 11.0",
  ilostat: "ILO (ILOSTAT)",
  faostat: "FAO (FAOSTAT)",
};
const pick = (cands, ok) => cands.find(ok) ?? cands[cands.length - 1];

function titleOf(ind, first, last) {
  const s = ind.shortVi;
  const cands =
    ind.source === "pink"
      ? [`Giá ${s} theo tháng ${first}–${last}: số liệu, CSV`, `Giá ${s} theo tháng ${first}–${last}`, `Giá ${s} ${first}–${last}`]
      : [
          `${cap(s)} Việt Nam ${first}–${last}: số liệu, biểu đồ, CSV`,
          `${cap(s)} Việt Nam ${first}–${last}: số liệu, CSV`,
          `${cap(s)} Việt Nam ${first}–${last}`,
          `${cap(s)} Việt Nam`,
        ];
  return pick(cands, t => t.length <= 60);
}

function descriptionOf(ind, first, last, hasPeers) {
  const src = SRC_SHORT[ind.source];
  const asean = hasPeers ? ", so sánh ASEAN" : "";
  let cands;
  if (ind.source === "pink") {
    cands = [
      `Giá ${ind.shortVi} theo tháng ${first}–${last} từ World Bank Pink Sheet: bảng bình quân năm, 24 tháng gần nhất, biểu đồ, tải CSV, trích dẫn APA.`,
      `Giá ${ind.shortVi} theo tháng ${first}–${last} (World Bank): bảng giá, biểu đồ, tải CSV, trích dẫn APA.`,
    ];
  } else {
    const base = [];
    if (!/Việt Nam/.test(ind.nameVi)) base.push(`${ind.nameVi}${/ của /.test(ind.nameVi) ? "," : " của"} Việt Nam ${first}–${last} theo ${src}: bảng từng năm, biểu đồ${asean}, tải CSV, trích dẫn APA.`);
    base.push(
      `${cap(ind.shortVi)} Việt Nam ${first}–${last} theo ${src}: bảng số liệu từng năm, biểu đồ${asean}, tải CSV miễn phí, trích dẫn APA.`,
      `${cap(ind.shortVi)} Việt Nam ${first}–${last} (${src}): bảng số liệu, biểu đồ, tải CSV, trích dẫn APA.`
    );
    cands = base;
  }
  const padded = cands.map(d => (d.length < 110 ? `${d} Miễn phí cho khoá luận, luận văn.` : d));
  return pick(padded, d => d.length >= 110 && d.length <= 160);
}

function varNameOf(ind) {
  let v = ind.code;
  if (ind.source === "wgi") v = v.replace(/^GOV_WGI_/, "wgi_");
  else if (ind.source === "pwt") v = `pwt_${v}`;
  else if (ind.source === "ilostat") v = `ilo_${v}`;
  return v
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "")
    .replace(/^(\d)/, "v$1")
    .slice(0, 32);
}

function urlsOf(ind, raw) {
  const c = encodeURIComponent(ind.code);
  switch (ind.source) {
    case "wdi":
      return { dataUrl: `https://data.worldbank.org/indicator/${c}?locations=VN`, apiUrl: `https://api.worldbank.org/v2/country/VNM/indicator/${c}?format=json&per_page=100` };
    case "wgi":
      return { dataUrl: "https://databank.worldbank.org/source/worldwide-governance-indicators", apiUrl: `https://api.worldbank.org/v2/country/VNM/indicator/${c}?source=3&format=json&per_page=100` };
    case "gfdd":
      return { dataUrl: "https://databank.worldbank.org/source/global-financial-development", apiUrl: `https://api.worldbank.org/v2/country/VNM/indicator/${c}?source=32&format=json&per_page=100` };
    case "pink":
      return { dataUrl: "https://www.worldbank.org/en/research/commodity-markets", apiUrl: raw.fileUrl ?? "https://www.worldbank.org/en/research/commodity-markets" };
    case "pwt":
      return { dataUrl: "https://www.rug.nl/ggdc/productivity/pwt/", apiUrl: "https://doi.org/10.34894/FABVLR" };
    case "ilostat": {
      const s = raw.series[ind.code];
      return { dataUrl: "https://ilostat.ilo.org/data/", apiUrl: `https://sdmx.ilo.org/rest/data/ILO,${s.flow}/VNM?format=csv` };
    }
    case "faostat":
      return { dataUrl: "https://www.fao.org/faostat/en/#data/PP", apiUrl: "https://bulks-faostat.fao.org/production/Prices_E_Asia.zip" };
  }
}

const written = [];
const kept = [];
const missing = [];
for (const ind of RICH) {
  const file = new URL(`${ind.slug}.json`, OUT_DIR);
  const raw = raws[ind.source];
  const s = raw?.series?.[ind.code];
  if (!s || s.values.length < 2) {
    (existsSync(file) ? kept : missing).push(`${ind.slug} (${ind.source}:${ind.code})`);
    continue;
  }
  const monthly = s.freq === "M";
  const values = s.values.map(([p, v]) =>
    monthly ? { year: Number(String(p).slice(0, 4)), month: Number(String(p).slice(5, 7)), value: clean(v) } : { year: Number(p), value: clean(v) }
  );
  const first = values[0].year;
  const last = values[values.length - 1].year;
  const comparison = monthly
    ? []
    : ASEAN_PEERS.filter(p => p.code !== "VNM" && (s.peers?.[p.code]?.length ?? 0) >= 2).map(p => ({
        code: p.code,
        name: p.name,
        values: s.peers[p.code].map(([y, v]) => ({ year: Number(y), value: clean(v) })),
      }));
  const src = SOURCES[ind.source];
  const doc = {
    source: ind.source,
    sourceName: src.name,
    publisher: src.org,
    code: ind.code,
    varName: varNameOf(ind),
    theme: ind.theme,
    kind: ind.source === "pink" ? "world" : "country",
    frequency: monthly ? "M" : "A",
    title: titleOf(ind, first, last),
    description: descriptionOf(ind, first, last, comparison.length > 0),
    shortVi: ind.shortVi,
    nameVi: ind.nameVi,
    nameEn: s.nameEn,
    unit: ind.unit,
    displayUnit: ind.displayUnit,
    scale: ind.scale,
    decimals: ind.decimals,
    explanation: ind.explanation,
    thesisUse: ind.thesisUse,
    sourceNote: s.note ?? "",
    sourceOrganization: s.org ?? src.org,
    lastUpdated: raw.lastUpdated,
    fetchedAt: raw.fetchedAt,
    license: src.license,
    licenseUrl: src.licenseUrl,
    termsUrl: src.termsUrl,
    ...urlsOf(ind, raw),
    citation: {
      author: src.apa.author,
      container: src.apa.container,
      ...(src.apa.publisher ? { publisher: src.apa.publisher } : {}),
      ...(src.apa.doi ? { doi: src.apa.doi } : {}),
      ...(src.apa.article ? { article: src.apa.article } : {}),
      ...(ind.source === "faostat" ? { licenceNote: "Licence: CC-BY-4.0." } : {}),
    },
    values,
    ...(comparison.length ? { comparison } : {}),
  };
  // Compact JSON: the files carry ASEAN peers and monthly series and would triple in size if indented.
  writeFileSync(file, JSON.stringify(doc) + "\n", "utf8");
  written.push(ind.slug);
}

// Remove page files whose indicator was taken off the editorial list.
const richSlugs = new Set(RICH.map(r => r.slug));
const removed = [];
for (const f of readdirSync(OUT_DIR)) {
  if (!f.endsWith(".json") || f.startsWith("_")) continue;
  const slug = f.slice(0, -5);
  if (!richSlugs.has(slug)) {
    unlinkSync(new URL(f, OUT_DIR));
    removed.push(slug);
  }
}

// ---------------------------------------------------------------- summary
console.log("\nSources:");
for (const r of summary) {
  console.log(
    `  ${r.id.padEnd(8)} ${r.status.padEnd(24)} ${String(r.series).padStart(5)} series${r.lastUpdated ? `  source updated ${r.lastUpdated}` : ""}${r.secs ? `  (${r.secs.toFixed(0)}s)` : ""}`
  );
}
const exploreCount = Object.values(raws).reduce((n, r) => n + (r ? Object.keys(r.series).length : 0), 0);
console.log(`\nRich pages: ${written.length} written, ${kept.length} kept from previous run, ${missing.length} missing, ${removed.length} removed.`);
if (kept.length) console.log(`  kept: ${kept.join(", ")}`);
if (missing.length) console.log(`  missing: ${missing.join(", ")}`);
if (removed.length) console.log(`  removed: ${removed.join(", ")}`);
console.log(`Explorer (Kho chỉ số): ${exploreCount} series across ${Object.values(raws).filter(Boolean).length} sources.`);
console.log(`Themes: ${THEMES.length}. Next: node scripts/check-data.mjs`);
if (summary.some(r => r.status.startsWith("FAILED")) || missing.length) process.exit(1);
